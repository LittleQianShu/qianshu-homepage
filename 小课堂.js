function pack(topics) {
    const out = {};
    const names = Object.keys(topics);
    for (let i = 0; i < names.length; i++) {
        const name = names[i];
        const rows = topics[name];
        out[name] = [];
        for (let n = 0; n < rows.length; n++) {
            out[name].push({ q: rows[n][0], a: rows[n][1] });
        }
    }
    return out;
}

