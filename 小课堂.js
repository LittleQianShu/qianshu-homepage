function growTopicQuiz(base, topic, level, seed) {
    const seen = {};
    const out = [];
    function add(row) {
        if (!row || seen[row.q]) {
            return;
        }
        seen[row.q] = true;
        out.push(row);
    }
    const start = base || [];
    for (let i = 0; i < start.length; i++) {
        add(start[i]);
    }
    const extra = makeTopicBits(topic, level, seed, QUIZ_NEED);
    for (let i = 0; i < extra.length && out.length < QUIZ_NEED; i++) {
        add(extra[i]);
    }
    return out;
}

